// Shared NOTA rule text for the resident ballot and the administrator preview.
export function NotaExplanation() {
  return (
    <p>
      NOTA means “None of the Above.” It is counted separately and cannot win.
      The candidate with the most votes among the candidates is elected, even if
      NOTA receives more votes. If no candidate receives any votes, no candidate
      is elected; tied candidate totals remain a tie.
    </p>
  );
}
